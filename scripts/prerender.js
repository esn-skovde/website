import puppeteer from 'puppeteer';
import { writeFileSync, mkdirSync, existsSync, createReadStream, statSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createServer } from 'http';

import { LANGUAGE_ALIASES, LANGUAGE_CODES } from '../src/lib/languages.js';
import { PAGE_SLUGS } from '../src/lib/routes.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');
const distDir = join(rootDir, 'dist');

/* The path the site is served from: "/" on esnskovde.org, "/<repo>/" on a
   GitHub project page. BASE_PATH arrives unset or empty at a domain root and as
   "/<repo>" (trailing slash stripped, as actions/configure-pages reports it) on
   a project page; both are normalised here. It has to match vite.config.js or
   the router's basename will not match the URLs this script visits. */
const rawBase = process.env.BASE_PATH || '/';
const base = rawBase.endsWith('/') ? rawBase : `${rawBase}/`;

// Languages and routes to prerender
// The app's own lists, so a new language or page cannot be left out of the build.
const languages = LANGUAGE_CODES;
const routes = ['', ...PAGE_SLUGS]; // '' is the home page

/* Sitemap metadata, keyed by the same `routes` list above so the two cannot
   drift apart. The hand-maintained public/sitemap.xml this replaces listed
   unprefixed URLs — /events, /board, /contact — which have never existed on
   this site: every page lives under a language prefix. All five <loc> values
   were dead, they contradicted the canonical each page emits, and the 42 real
   language pages were not listed at all. (They now redirect to the real pages;
   see writeLegacyRedirects.) */
const SITE = 'https://esnskovde.org';
const routeMeta = {
    '': { changefreq: 'weekly', priority: '1.0' },
    'events': { changefreq: 'daily', priority: '0.9' },
    'new-to-skovde': { changefreq: 'monthly', priority: '0.8' },
    'board': { changefreq: 'monthly', priority: '0.8' },
    'esn-card': { changefreq: 'monthly', priority: '0.7' },
    'contact': { changefreq: 'monthly', priority: '0.6' },
};

// Has to match the canonical SEO.jsx emits exactly, or the sitemap and the page
// contradict each other and the page wins. Both end in a slash: GitHub Pages
// serves a page only at /en/events/ and redirects /en/events there.
const canonical = (lang, route) => (route ? `${SITE}/${lang}/${route}/` : `${SITE}/${lang}/`);

function writeSitemap() {
    const lastmod = new Date().toISOString().slice(0, 10);
    const urls = [];

    for (const route of routes) {
        const { changefreq, priority } = routeMeta[route];
        const alternates = [
            ...languages.map(
                (code) =>
                    `    <xhtml:link rel="alternate" hreflang="${code}" href="${canonical(code, route)}"/>`
            ),
            `    <xhtml:link rel="alternate" hreflang="x-default" href="${canonical('en', route)}"/>`,
        ].join('\n');

        for (const lang of languages) {
            urls.push(
                [
                    '  <url>',
                    `    <loc>${canonical(lang, route)}</loc>`,
                    `    <lastmod>${lastmod}</lastmod>`,
                    `    <changefreq>${changefreq}</changefreq>`,
                    `    <priority>${priority}</priority>`,
                    alternates,
                    '  </url>',
                ].join('\n')
            );
        }
    }

    const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prerender.js. Do not edit by hand — a hand-kept copy
     is exactly what drifted into advertising five URLs that do not exist. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`;

    writeFileSync(join(distDir, 'sitemap.xml'), xml, 'utf-8');
    console.log(`Wrote sitemap.xml (${urls.length} URLs)`);
}

/* The old sitemap's URLs, /events and the rest, are still in search results,
   bookmarks and printed QR codes, and Pages served them the 404 page, which
   the app then sent to the English home page. Each now gets a page of its
   own that moves on to the page itself, in the language the app would pick
   at "/": the visitor's stored choice, then their browser's languages, by the
   same rule as canonicalLanguage() in src/lib/languages.js. The refresh to
   English sits in <noscript>, for visitors without scripting only: left to
   race the script's redirect, it could win and override the visitor's
   language. Not in the sitemap: these are redirects, not pages. */
function writeLegacyRedirects() {
    for (const slug of PAGE_SLUGS) {
        const fallback = `${base}en/${slug}/`;
        const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="robots" content="noindex">
<title>ESN Skövde</title>
<link rel="canonical" href="${canonical('en', slug)}">
<script>
(function () {
  var codes = ${JSON.stringify(languages)}, aliases = ${JSON.stringify(LANGUAGE_ALIASES)};
  var pick = function (tag) {
    var code = String(tag || "").toLowerCase().split(/[-_]/)[0];
    code = aliases.hasOwnProperty(code) ? aliases[code] : code;
    return codes.indexOf(code) > -1 ? code : null;
  };
  var lang = null;
  try { lang = pick(localStorage.getItem("i18nextLng")); } catch (e) { /* storage blocked */ }
  var wanted = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  for (var i = 0; !lang && i < wanted.length; i++) lang = pick(wanted[i]);
  location.replace(${JSON.stringify(base)} + (lang || "en") + "/${slug}/" + location.search + location.hash);
})();
</script>
<noscript><meta http-equiv="refresh" content="0; url=${fallback}"></noscript>
</head>
<body>
<p><a href="${fallback}">${fallback}</a></p>
</body>
</html>
`;
        const dir = join(distDir, slug);
        mkdirSync(dir, { recursive: true });
        writeFileSync(join(dir, 'index.html'), html, 'utf-8');
    }
    console.log(`Wrote ${PAGE_SLUGS.length} redirects from the old unprefixed URLs`);
}

// Generate all routes, at the slash form the site is served from
const allRoutes = ['/']; // Start with root
languages.forEach((lang) => {
    routes.forEach((route) => {
        const path = route ? `/${lang}/${route}/` : `/${lang}/`;
        allRoutes.push(path);
    });
    // Add 404 page for each language
    allRoutes.push(`/${lang}/404/`);
});

/* The page every route starts from: the shell `vite build` wrote, with an
   empty #root. It is read once, up front, because the first route saved is
   "/" and it overwrites dist/index.html with the English home page. Served
   from disk, that snapshot became the starting page for every route after
   it, and the app takes a filled #root for the page's own prerendered HTML:
   it would render each route as a repaint of a page already on screen,
   without the entrance animations, and bake that into the snapshot. */
function readShell() {
    const shell = readFileSync(join(distDir, 'index.html'), 'utf-8');
    if (!shell.includes('<div id="root"></div>')) {
        throw new Error('dist/index.html is not the empty shell `vite build` writes; build before prerendering');
    }
    return shell;
}

// Simple static file server
function createStaticServer(port, shell) {
    return new Promise((resolve) => {
        const server = createServer((req, res) => {
            // dist/ is the site root whatever the public base path is, so strip
            // the prefix the built HTML asks for before looking anything up.
            const url = base !== '/' && req.url.startsWith(base)
                ? req.url.slice(base.length - 1)
                : req.url;

            let filePath = join(distDir, url === '/' ? 'index.html' : url);

            // Handle directory requests
            if (url.endsWith('/') && url !== '/') {
                filePath = join(distDir, url, 'index.html');
            }

            // "/" and every SPA route get the shell, never a snapshot.
            if (url === '/' || !existsSync(filePath) || statSync(filePath).isDirectory()) {
                res.writeHead(200, { 'Content-Type': 'text/html' });
                res.end(shell);
                return;
            }

            const ext = filePath.split('.').pop();
            const contentType = {
                'html': 'text/html',
                'js': 'application/javascript',
                'css': 'text/css',
                'json': 'application/json',
                'png': 'image/png',
                'jpg': 'image/jpeg',
                'jpeg': 'image/jpeg',
                'gif': 'image/gif',
                'svg': 'image/svg+xml',
                'ico': 'image/x-icon',
            }[ext] || 'application/octet-stream';

            res.writeHead(200, { 'Content-Type': contentType });
            createReadStream(filePath).pipe(res);
        });

        server.listen(port, () => {
            console.log(`Static server running on http://localhost:${port}`);
            resolve(server);
        });
    });
}

/* What "still loading" looks like on a page: every placeholder is a
   Skeleton (src/components/ui/Skeleton.jsx), the only thing that uses
   animate-pulse. A page is not saved while one is showing, and how long to wait
   for the data to arrive is bounded: the client itself keeps retrying a failed
   query for about 7 seconds before it gives up and shows its error. */
const PENDING_SELECTOR = '.animate-pulse';
const DATA_WAIT_MS = 15000;

// Routes that were refused because Supabase did not deliver their events.
const noData = [];

/* Renders one route and saves it. Returns false, having logged why, when the
   route failed: the caller decides what a failure means for the build. */
async function prerenderRoute(browser, route, port) {
    const page = await browser.newPage();

    // What SEO.jsx has to end up stamping for this route. "/" follows the
    // language redirect to the English home page; "/sv/404/" is the page "404"
    // in Swedish.
    const [expectedLang = 'en', ...pageParts] = route.split('/').filter(Boolean);
    const expectedCanonical = canonical(expectedLang, pageParts.join('/'));

    // An uncaught exception fails the route even when the page looks finished:
    // whatever threw did not run to completion.
    const pageErrors = [];
    page.on('pageerror', (error) => pageErrors.push(error?.message ?? String(error)));

    /* How the page's requests for the events went. The placeholders show that
       a query is still open; these show the other way a build ends up without
       its events, a query that has failed for good, where the page then swaps
       the placeholders for an error and has nothing left to wait for. Only the
       events table counts: the trips are optional, and a site without them has
       always been fine. A failure that a later try got past does not count. */
    let eventsOk = 0;
    let eventsFailed = 0;
    const isEventsQuery = (request) =>
        request.method() === 'GET' && /\/rest\/v1\/events(\?|$)/.test(request.url());
    page.on('requestfinished', (request) => {
        if (!isEventsQuery(request)) return;
        if (request.response()?.ok()) eventsOk++;
        else eventsFailed++;
    });
    page.on('requestfailed', (request) => {
        if (isEventsQuery(request)) eventsFailed++;
    });

    try {
        console.log(`Rendering: ${route}`);

        /* The app formats dates in the venue's time zone wherever it runs
           (see src/lib/dates.js). Emulating it here as well keeps anything
           that still reads the local clock on the venue's day, on a CI runner
           in UTC as on a laptop in India. */
        await page.emulateTimezone('Europe/Stockholm');

        /* Tells the app it is being saved as the static page (see
           src/lib/prerender.js), so it leaves out what is only true on the
           day of the build: an "In 2 days" label is wrong by tomorrow. */
        await page.evaluateOnNewDocument(() => {
            window.__PRERENDER__ = true;
        });

        /* The theme is the visitor's to pick, not the build machine's. The app
           follows the operating system until told otherwise, and this browser
           followed the build machine's: every snapshot came out dark on a dark
           Mac and light on CI. Pinning it makes the render the same anywhere. */
        await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'light' }]);

        // Navigate to the route, under the public base path so that the
        // router's basename matches and the app renders rather than 404ing.
        const url = base === '/' ? route : `${base.slice(0, -1)}${route}`;

        /* Loads the route and waits for it to settle. Returns why its data did
           not arrive, or nothing when it did. A function, so that a page whose
           data did not arrive can be loaded a second time. */
        const load = async () => {
            eventsOk = 0;
            eventsFailed = 0;

            await page.goto(`http://localhost:${port}${url}`, {
                waitUntil: 'networkidle0',
                timeout: 30000,
            });

            /* Wait for SEO.jsx to stamp this route's own canonical, and fail the
               route if it never does. Finding a canonical at all proved nothing:
               the HTML this server hands out can already carry one from an
               earlier snapshot. The error boundary ends the wait early, since
               SEO.jsx will then never run; the checks below report it. */
            await page
                .waitForFunction(
                    (href) =>
                        document.querySelector('[data-error-boundary]') !== null ||
                        document.querySelector('link[data-seo][rel="canonical"]')?.getAttribute('href') === href,
                    { timeout: 15000 },
                    expectedCanonical
                )
                .catch((error) => {
                    throw new Error(`SEO.jsx never set the canonical to ${expectedCanonical} (${error.message})`);
                });

            // Additional wait for any lazy-loaded content
            await new Promise(resolve => setTimeout(resolve, 1000));

            /* With Supabase credentials the events arrive after the page has
               rendered, and a build whose Supabase could not be reached used to
               save the placeholders: networkidle0 and the second above are over
               long before the client has given up retrying, and the page still
               passed every check below. Nothing is waited for when nothing is
               loading, as on every build without credentials. */
            const stuck = await page
                .waitForFunction((selector) => !document.querySelector(selector), { timeout: DATA_WAIT_MS, polling: 250 }, PENDING_SELECTOR)
                .then(() => false, () => true);

            const reasons = [];
            if (stuck) reasons.push(`loading placeholders still showing after ${DATA_WAIT_MS / 1000} s`);
            if (eventsFailed && !eventsOk) reasons.push('the request for the events failed');
            return reasons;
        };

        let unfinished = await load();
        if (unfinished.length) {
            console.warn(`  ${route}: ${unfinished.join('; ')}. Loading it once more.`);
            pageErrors.length = 0;
            unfinished = await load();
        }
        if (unfinished.length) {
            noData.push(route);
            throw new Error(
                `Supabase did not deliver the events (${unfinished.join('; ')}). It may be unreachable or paused. ` +
                    'A page with placeholders or an error where the events belong is not saved'
            );
        }

        /* Refuse to save a page that did not render as itself. The error
           boundary, a Suspense spinner or an empty #root is still HTML, and it
           used to be written and deployed exactly as if it were the page. */
        const problems = await page.evaluate(
            ({ lang, href }) => {
                const found = [];
                const h1s = document.querySelectorAll('h1').length;
                if (h1s !== 1) found.push(`${h1s} <h1> elements, expected exactly one`);
                if (document.querySelector('[data-error-boundary]')) {
                    found.push('the error boundary rendered instead of the page');
                }
                if (document.documentElement.lang !== lang) {
                    found.push(`<html lang="${document.documentElement.lang}">, expected "${lang}"`);
                }
                if (!document.getElementById('root')?.firstElementChild) found.push('#root is empty');
                const actual = document.querySelector('link[data-seo][rel="canonical"]')?.getAttribute('href');
                if (actual !== href) found.push(`canonical ${actual ?? '(none)'}, expected ${href}`);
                return found;
            },
            { lang: expectedLang, href: expectedCanonical }
        );
        if (pageErrors.length) problems.push('the page threw an uncaught error while rendering');
        if (problems.length) throw new Error(problems.join('; '));

        /* Puts <html> and <head> back the way index.html has them. The app
           writes to both while it runs, and what it wrote belongs to this
           render, not to the visitor:

           - The theme. The inline script in index.html sets the dark class
             and the color-scheme before the first paint of whoever opens the
             page, from their own setting. Saved, they gave every visitor
             without scripting the theme of the machine that built the page,
             and every visitor with it the wrong color-scheme until the bundle
             ran.
           - GuideNav's measured --guide-nav-height. That measures this
             render's window, not the visitor's: saved into the page it
             overrode index.css's defaults, and without JS the guide's anchors
             landed under the two-row rail on a desktop. The app measures it
             again when it starts.
           - Sonner's stylesheet. Sonner adds it to <head> whenever its module
             loads, so it was in every render, 15 kB a page, and the app then
             added a second copy beside it. A snapshot has no toast open, so
             nothing in it needs the styles before the app starts.
           - The media of the Lato stylesheet link. index.html loads it as
             print and the link switches itself on once it has loaded, which
             it has by now. Saved as "all", it would hold up the first paint
             of every page again.

           Taking the last property off leaves class="" or style="" behind;
           those go too. */
        await page.evaluate(() => {
            const html = document.documentElement;
            html.classList.remove('dark');
            html.style.removeProperty('color-scheme');
            html.style.removeProperty('--guide-nav-height');
            for (const name of ['class', 'style']) {
                if (!html.getAttribute(name)) html.removeAttribute(name);
            }

            for (const style of document.head.querySelectorAll('style')) {
                if (style.textContent.includes('[data-sonner-toaster]')) style.remove();
            }

            document
                .querySelector('link[rel="stylesheet"][href^="https://fonts.googleapis.com/"]')
                ?.setAttribute('media', 'print');
        });

        // Get the rendered HTML
        const html = await page.content();

        // Determine output path
        let outputPath;
        if (route === '/') {
            outputPath = join(distDir, 'index.html');
        } else {
            // Create directory structure: /en/events/ -> dist/en/events/index.html
            const pathParts = route.split('/').filter(Boolean);
            const lang = pathParts[0];
            const pagePath = pathParts.slice(1).join('/');

            if (pagePath) {
                // Has page path: /en/events/ -> dist/en/events/index.html
                const dirPath = join(distDir, lang, pagePath);
                mkdirSync(dirPath, { recursive: true });
                outputPath = join(dirPath, 'index.html');
            } else {
                // Just language: /en/ -> dist/en/index.html
                const dirPath = join(distDir, lang);
                mkdirSync(dirPath, { recursive: true });
                outputPath = join(dirPath, 'index.html');
            }
        }

        // Fix asset paths in the HTML for nested directories
        // Calculate relative path depth: /en/events/ -> ../../, /en/ -> ../
        // Depth = number of directories we're nested in
        const depth = route === '/' ? 0 : route.split('/').filter(Boolean).length;
        const basePath = depth === 0 ? '' : '../'.repeat(depth);

        let fixedHtml = html;

        /* Vite's runtime preload helper injects <link rel="modulepreload"
           as="script"> for every chunk it pulls in, and page.content() captures
           them, so each snapshot froze in whatever this one render happened to
           touch. Every page ended up preloading the Home route, the events
           module, the 215 kB Supabase client and the sample-data fixtures —
           none of which /board or /contact ever uses. Vite's own build-time
           preloads (no as="script") are the real ones and stay. */
        fixedHtml = fixedHtml.replace(
            /\s*<link[^>]*rel="modulepreload"[^>]*\bas="script"[^>]*>/g,
            ''
        );

        /* Only for a root-served site. Under a base path the emitted URLs are
           already the correct absolute ones, and rewriting them would break them.

           The icon links (/favicon.ico, /logo.png) are deliberately not in this
           list. A stylesheet or script URL is read once, when the page loads, so
           a relative one is safe. Chrome resolves an icon link against the
           page's current URL, and the link survives a client-side navigation:
           "../favicon.ico" on /en/ is /favicon.ico, but after a click on to
           /en/events/ or a language switch to /sv/ it asked for
           /en/favicon.ico or /sv/favicon.ico, which are 404s. */
        if (depth > 0 && base === '/') {
            fixedHtml = fixedHtml
                .replace(/href="\/(assets\/[^"]+)"/g, `href="${basePath}$1"`)
                .replace(/src="\/(assets\/[^"]+)"/g, `src="${basePath}$1"`)
                .replace(/href="\/(robots\.txt)"/g, `href="${basePath}$1"`)
                .replace(/href="\/(sitemap\.xml)"/g, `href="${basePath}$1"`);
        }

        // Write the HTML file
        writeFileSync(outputPath, fixedHtml, 'utf-8');
        console.log(`Saved: ${outputPath}`);
        return true;

    } catch (error) {
        console.error(`Error rendering ${route}:`, error.message);
        for (const message of pageErrors) console.error(`  uncaught in the page: ${message}`);
        return false;
    } finally {
        await page.close();
    }
}

async function prerender() {
    console.log('Starting Static Site Generation...\n');
    console.log(`Base path: ${base}`);
    console.log(`Routes to prerender: ${allRoutes.length}\n`);

    // Start static server
    const port = 4173; // Vite preview default port
    const server = await createStaticServer(port, readShell());

    /* Launched inside the try, so that a browser which cannot start still
       reaches the finally. Outside it, a missing Chrome skipped server.close(),
       and the still-listening server kept Node alive: the build hung forever
       instead of failing. */
    let browser;
    try {
        console.log('Launching browser...\n');
        browser = await puppeteer.launch({
            headless: true,
            /* "/" is rendered by following the visitor's-language redirect, so
               the root page comes out in whatever language the browser reports.
               --lang alone does not pin that everywhere (macOS ignores it);
               --accept-lang sets navigator.language directly. */
            args: ['--no-sandbox', '--disable-setuid-sandbox', '--lang=en-US', '--accept-lang=en-US'],
        });

        // Prerender all routes, keeping every one that failed.
        const failures = [];
        for (const route of allRoutes) {
            if (!(await prerenderRoute(browser, route, port))) failures.push(route);
        }

        /* Stop before anything below runs: the root 404.html is copied from
           /en/404, and the sitemap lists every route whether or not its page
           was written. */
        if (failures.length) {
            throw new Error(
                `${failures.length} of ${allRoutes.length} routes failed to prerender: ${failures.join(', ')}` +
                    (noData.length
                        ? `\n${noData.length} of them could not get their events from Supabase. If the project is paused or down, bring it back and build again.`
                        : '')
            );
        }

        // Also create a root-level 404.html for GitHub Pages
        // This will be served when a route doesn't exist
        console.log('Creating root 404.html for GitHub Pages...');
        const root404Path = join(distDir, '404.html');
        const en404Path = join(distDir, 'en', '404', 'index.html');

        if (existsSync(en404Path)) {
            // Copy the English 404 page as the root 404.html
            const en404Content = readFileSync(en404Path, 'utf-8');
            // Fix asset paths for root level. Under a base path nothing was made
            // relative in the first place, so there is nothing to undo.
            const root404Content = base !== '/' ? en404Content : en404Content
                .replace(/href="\.\.\/\.\.\/(assets\/[^"]+)"/g, 'href="/$1"')
                .replace(/src="\.\.\/\.\.\/(assets\/[^"]+)"/g, 'src="/$1"');
            writeFileSync(root404Path, root404Content, 'utf-8');
            console.log('Created root 404.html');
        }

        writeLegacyRedirects();
        writeSitemap();

        console.log(`Successfully prerendered ${allRoutes.length} routes!\n`);

    } finally {
        await browser?.close();
        server.close();
    }
}

// Run prerender. Every failure has to reach the exit code, or the build step
// passes and CI deploys whatever happened to be written.
prerender().catch((error) => {
    console.error('Prerendering failed:', error);
    process.exit(1);
});

